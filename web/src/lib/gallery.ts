import manifest from "@/content/gallery/manifest.json";
import { downloadBlob } from "./export";

export type GalleryFormat = "png" | "jpeg" | "webp";

export type GalleryWallpaper = {
  slug: string;
  title: string;
  /** Display name of the painter, resolved from the prompt this was generated with. */
  painter: string;
  /** Matches a file in src/content/prompts, so the card can link to /prompts. */
  promptSlug: string;
  /** Master filename, relative to the gallery base — the byte-for-byte download. */
  file: string;
  format: GalleryFormat;
  bytes: number;
  width: number;
  height: number;
  thumb: string;
  thumbWidth: number;
  thumbHeight: number;
  /** Inline data URI, ~400 bytes, painted under the thumbnail while it loads. */
  blur: string;
  addedAt: string;
};

/**
 * The one place that knows where the files physically live. Masters ship inside
 * public/gallery today; pointing NEXT_PUBLIC_GALLERY_BASE_URL at a bucket moves
 * the whole gallery to object storage without touching a component.
 */
const BASE = (process.env.NEXT_PUBLIC_GALLERY_BASE_URL ?? "/gallery").replace(/\/+$/, "");

export function galleryAssetUrl(path: string) {
  return `${BASE}/${path}`;
}

/**
 * Read from the manifest generated by scripts/build-gallery.mjs. It is imported
 * rather than read from disk so nothing touches the filesystem at runtime —
 * `output: "standalone"` only ships the traced module graph.
 */
export function loadGallery(): GalleryWallpaper[] {
  return manifest as GalleryWallpaper[];
}

/** Painters present in the gallery, in the order they first appear. */
export function galleryPainters(wallpapers: GalleryWallpaper[]) {
  const seen = new Map<string, { promptSlug: string; painter: string; count: number }>();
  for (const wallpaper of wallpapers) {
    const entry = seen.get(wallpaper.promptSlug);
    if (entry) entry.count += 1;
    else seen.set(wallpaper.promptSlug, { promptSlug: wallpaper.promptSlug, painter: wallpaper.painter, count: 1 });
  }
  return [...seen.values()].sort((a, b) => a.painter.localeCompare(b.painter, "fr"));
}

export const FORMAT_LABELS: Record<GalleryFormat, string> = {
  png: "PNG",
  jpeg: "JPEG",
  webp: "WebP",
};

/**
 * Hands the master over untouched — no canvas, no re-encoding, so "full quality"
 * means the exact bytes that were committed.
 *
 * Same-origin uses a native <a download>: the browser streams it, shows its own
 * progress and never buffers 20 MB in memory. Cross-origin (a CDN base URL) has
 * to go through fetch, because `download` is ignored on a foreign origin.
 */
export async function downloadWallpaper(wallpaper: GalleryWallpaper) {
  const url = galleryAssetUrl(wallpaper.file);
  const sameOrigin = !/^https?:\/\//i.test(url) || new URL(url, location.href).origin === location.origin;

  if (sameOrigin) {
    const link = document.createElement("a");
    link.href = url;
    link.download = wallpaper.file;
    document.body.appendChild(link);
    link.click();
    link.remove();
    return;
  }

  const response = await fetch(url);
  if (!response.ok) throw new Error("Le téléchargement a échoué.");
  downloadBlob(await response.blob(), wallpaper.file);
}
